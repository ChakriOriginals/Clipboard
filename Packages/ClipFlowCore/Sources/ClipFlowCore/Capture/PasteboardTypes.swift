/// Pasteboard flavor identifiers ClipFlow understands (SECURITY_MODEL §5–6).
public enum PasteboardType {
    public static let plainText = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let html = "public.html"
    public static let url = "public.url"
    public static let fileURL = "public.file-url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"

    /// The only flavors ever read or stored.
    public static let allowlist: Set<String> = [plainText, rtf, html, url, fileURL, png, tiff]

    /// Markers set by password managers and similar tools (nspasteboard.org conventions).
    /// Any of these present means the pasteboard is never captured.
    public static let neverCapture: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]
}
